-- PowerSync sync support: create the `powersync` logical-replication
-- publication (the name is contractual — the PowerSync service connects to a
-- publication named exactly `powersync`) with an explicit v1 table list.
-- Never `FOR ALL TABLES`: the service must read everything in the
-- publication, so unrelated high-churn tables would spike memory and lag.
--
-- v1 table list (all public schema; consumer/courier read-sync domains that
-- exist in the authoritative SQL migrations, not just drizzle/schema.ts):
--
--   Consumer / shared per-user:
--     public.orders                  (0000) consumer order list + courier/merchant scoping key
--     public.order_tracking_events   (0003) consumer order tracking timeline
--     public.notifications           (0000) notification history
--     public.support_tickets         (0000) support-case read model (pairs with
--                                          the /api/powersync/upload whitelist)
--     public.loyalty_points          (init-local-postgres) loyalty balance/tier
--     public.loyalty_transactions    (init-local-postgres) loyalty journal
--     public.loyalty_rewards         (init-local-postgres) reward catalog
--     public.loyalty_redemptions     (init-local-postgres) consumer redemptions
--     public.consumer_memberships    (0003) membership state
--     public.consumer_reviews        (0003) consumer's own reviews
--   Courier:
--     public.drivers                 (0000) token sub -> driver_id parameter mapping.
--                                    CHURN CAVEAT: current_latitude/longitude
--                                    updates flow through the publication. If
--                                    location write churn becomes a replication-
--                                    lag problem, upgrade to a PG15+ column-list
--                                    publication excluding the location columns,
--                                    or move live location reads to the
--                                    vehicle-tracker pipeline entirely.
--     public.driver_reviews          (0000) courier ratings
--     public.driver_performance_scores (0003) courier scorecard
--     public.delivery_tracking_events (0023) courier/ops position events
--   Merchant:
--     public.service_providers       (0000) merchant store identity + directory
--     public.provider_catalog_items  (0003) merchant catalog
--   Global reference (small, shared buckets):
--     public.service_verticals       (0000) vertical directory
--     public.vertical_service_templates (0003) vertical templates
--     public.membership_plans        (0003) plan catalog
--
-- Deliberately EXCLUDED:
--   - money movement: transactions, wallets, ledger_*, mojaloop_*,
--     payout_settlements, merchant_reserves, treasury_reserves (TigerBeetle is
--     the money engine; ledger rows must not fan out to client devices)
--   - verification PII payloads: verification.*, rider_verifications,
--     rider_name_screenings, document forensics/extraction tables
--   - auth/session state: session_revocations, operator_security_sessions,
--     operator_credentials, account_lifecycle_tokens
--   - blob-adjacent rows: delivery_proofs, delivery_proof_upload_grants
--     (object-key payloads; proof media lives in object storage)
--   - high-churn telemetry/ops streams: audit_logs, driver location event
--     streams, telematics, operational_events, push_notification_tokens
--     (device tokens are credential-adjacent PII)
--   - no table here carries >15MB rows (PowerSync max row size); the largest
--     text/jsonb columns on this list are review feedback and notification
--     metadata, both small by construction.
--
-- To extend: add the table to sync-rules.yaml buckets first (or in the same
-- change), then append another guarded DO block below in a NEW migration —
-- do not edit this file after it has shipped.
--
-- Idempotent: every step is a DO block guarded on pg_publication /
-- pg_publication_tables / pg_class / pg_roles so replays are no-ops.
-- Applies after 0102_dispute_idempotency_replay_checks.sql.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'powersync') THEN
    CREATE PUBLICATION powersync;
  END IF;
END $$;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relname = 'orders')
     AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'powersync' AND schemaname = 'public' AND tablename = 'orders') THEN
    ALTER PUBLICATION powersync ADD TABLE public.orders;
  END IF;
END $$;

