-- Read-only grants for the least-privilege replication role (created by the
-- role SQL in deploy/powersync/README.md). Guarded on the role existing and
-- granted per-table only when the table exists (some v1 tables come from
-- scripts/init-local-postgres.sql), so this migration applies cleanly in any
-- provisioning order and stays rerun-safe.
DO $$
DECLARE
  v_table text;
BEGIN
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname = 'powersync_replication') THEN
    FOREACH v_table IN ARRAY ARRAY[
      'orders', 'order_tracking_events', 'notifications', 'support_tickets',
      'loyalty_points', 'loyalty_transactions', 'loyalty_rewards',
      'loyalty_redemptions', 'consumer_memberships', 'consumer_reviews',
      'drivers', 'driver_reviews', 'driver_performance_scores',
      'delivery_tracking_events', 'service_providers', 'provider_catalog_items',
      'service_verticals', 'vertical_service_templates', 'membership_plans'
    ] LOOP
      IF EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relname = v_table AND c.relkind IN ('r', 'p')
      ) THEN
        EXECUTE format('GRANT SELECT ON public.%I TO powersync_replication', v_table);
      END IF;
    END LOOP;
  END IF;
END $$;
